def seed_blog_posts(apps, schema_editor):
    BlogPost = apps.get_model("main", "BlogPost")
    now = timezone.now()
    created_posts = []

    for index, post_data in enumerate(POSTS):
        post, _ = BlogPost.objects.update_or_create(
            slug=post_data["slug"],
            defaults={
                "title": post_data["title"],
                "excerpt": post_data["excerpt"],
                "body": post_data["body"],
                "author_name": "تیم تحقیق و توسعه شرکت وزنه",
                "published_at": now - timedelta(days=index * 9),
                "is_published": True,
                "is_featured": post_data["featured"],
            },
        )
        created_posts.append(post)

    for index, post in enumerate(created_posts):
        related = [
            created_posts[(index + offset) % len(created_posts)]
            for offset in (1, 2, 3)
        ]
        post.related_posts.set(related)


def remove_seeded_blog_posts(apps, schema_editor):
    BlogPost = apps.get_model("main", "BlogPost")
    BlogPost.objects.filter(slug__in=[post["slug"] for post in POSTS]).delete()


